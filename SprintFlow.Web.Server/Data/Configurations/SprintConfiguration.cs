using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class SprintConfiguration : IEntityTypeConfiguration<Sprint>
{
    public void Configure(EntityTypeBuilder<Sprint> builder)
    {
        // A sprint covering no days is not a sprint, so the two dates being equal is refused too.
        // This is a single-row rule, which is the only kind a CHECK constraint can express — the
        // "no two sprints overlap" rule needs to see other rows and lives in SprintService instead.
        builder.ToTable("Sprints", table =>
            table.HasCheckConstraint("CK_Sprints_EndAfterStart", "[EndDate] > [StartDate]"));

        builder.HasKey(s => s.SprintId);

        // Exists only so a Task's foreign key can name the sprint AND its board together. Same
        // technique WorkflowColumns already uses, and for the same reason.
        builder.HasAlternateKey(s => new { s.SprintId, s.BoardId });

        builder.Property(s => s.Name)
            .IsRequired()
            .HasMaxLength(200);

        // date, not datetime2. DateOnly already maps this way by convention; saying so here means
        // the guarantee is written down rather than inherited, because the whole day-based design
        // rests on it: a column of this type has no time of day to store and no offset to shift it.
        builder.Property(s => s.StartDate)
            .IsRequired()
            .HasColumnType("date");

        builder.Property(s => s.EndDate)
            .IsRequired()
            .HasColumnType("date");

        // Generated by the database, as everywhere else. This one is an audit timestamp rather than
        // one of the sprint's own days, so it stays a datetime2.
        builder.Property(s => s.CreatedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // Cascade: a sprint cannot exist without its board.
        builder.HasOne(s => s.Board)
            .WithMany(b => b.Sprints)
            .HasForeignKey(s => s.BoardId)
            .OnDelete(DeleteBehavior.Cascade);

        // Restrict, like everywhere else: removing a user must never delete their work.
        builder.HasOne(s => s.CreatedByUser)
            .WithMany()
            .HasForeignKey(s => s.CreatedByUserId)
            .OnDelete(DeleteBehavior.Restrict);

        // Both things that read sprints read them per board and in date order: the list on the
        // Sprints page, and the overlap check that runs before every create.
        builder.HasIndex(s => new { s.BoardId, s.StartDate });
    }
}
