using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class BoardConfiguration : IEntityTypeConfiguration<Board>
{
    public void Configure(EntityTypeBuilder<Board> builder)
    {
        builder.ToTable("Boards");

        builder.HasKey(b => b.BoardId);

        // Exists only so a Team's foreign key can point at the board AND its creator together.
        // BoardId alone is already the primary key, so this constraint adds no real restriction on
        // Boards — it just gives the composite relationship something to reference.
        builder.HasAlternateKey(b => new { b.BoardId, b.CreatedByUserId });

        // Not unique, for the same reason Area names are not: nothing in the domain requires it.
        builder.Property(b => b.Name)
            .IsRequired()
            .HasMaxLength(200);

        // Generated by the database, as Areas.CreatedDate is: the client cannot supply it, and the
        // value comes back without a UTC offset so the browser cannot shift the displayed day.
        builder.Property(b => b.CreatedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // Cascade: a Board cannot exist without its Area, so removing an Area must take its Boards
        // with it. This is also what keeps a future "delete Area" from needing manual cleanup.
        builder.HasOne(b => b.Area)
            .WithMany(a => a.Boards)
            .HasForeignKey(b => b.AreaId)
            .OnDelete(DeleteBehavior.Cascade);

        // Restrict, like everywhere else: removing a user must never delete their work.
        builder.HasOne(b => b.CreatedByUser)
            .WithMany()
            .HasForeignKey(b => b.CreatedByUserId)
            .OnDelete(DeleteBehavior.Restrict);
    }
}
