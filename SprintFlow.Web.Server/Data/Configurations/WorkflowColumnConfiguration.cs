using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class WorkflowColumnConfiguration : IEntityTypeConfiguration<WorkflowColumn>
{
    public void Configure(EntityTypeBuilder<WorkflowColumn> builder)
    {
        builder.ToTable("WorkflowColumns");

        builder.HasKey(c => c.WorkflowColumnId);

        // Exists only so a Task's foreign key can name the column AND its board together.
        // WorkflowColumnId alone is already the primary key, so this adds no real restriction here
        // — it just gives the composite relationship something to reference. Same technique the
        // Team-owner invariant already uses on Boards.
        builder.HasAlternateKey(c => new { c.WorkflowColumnId, c.BoardId });

        builder.Property(c => c.Name)
            .IsRequired()
            .HasMaxLength(100);

        // Generated by the database, as everywhere else: the client cannot supply it, and the value
        // comes back without a UTC offset so the browser cannot shift the displayed day.
        builder.Property(c => c.CreatedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // Cascade: a column cannot exist without its board.
        builder.HasOne(c => c.Board)
            .WithMany(b => b.WorkflowColumns)
            .HasForeignKey(c => c.BoardId)
            .OnDelete(DeleteBehavior.Cascade);

        // Reading a board means reading its columns in order, so the index carries both.
        builder.HasIndex(c => new { c.BoardId, c.Position });

        // Filtered, so it constrains the system columns without touching custom ones: a board may
        // hold any number of columns whose kind is null, but only one To Do, one Completed and one
        // Cancelled. "At most one of each" therefore holds in the database, not just in a service.
        builder.HasIndex(c => new { c.BoardId, c.SystemKind })
            .IsUnique()
            .HasFilter("[SystemKind] IS NOT NULL");
    }
}
