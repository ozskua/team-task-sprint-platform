using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class AreaConfiguration : IEntityTypeConfiguration<Area>
{
    public void Configure(EntityTypeBuilder<Area> builder)
    {
        builder.ToTable("Areas");

        builder.HasKey(a => a.AreaId);

        // Deliberately not unique: two Areas may share a name. Nothing in the domain model requires
        // uniqueness, and inventing that rule here would be a decision the model has not made.
        builder.Property(a => a.Name)
            .IsRequired()
            .HasMaxLength(200);

        // Generated by the database, exactly as Users.CreatedDate is. Two reasons: the client can
        // never supply it, and the value comes back with an unspecified kind, so it serializes
        // without a UTC offset and the browser cannot shift it to the previous or next day.
        builder.Property(a => a.CreatedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // Restrict, not Cascade: removing a user must never delete the Areas they created.
        builder.HasOne(a => a.CreatedByUser)
            .WithMany()
            .HasForeignKey(a => a.CreatedByUserId)
            .OnDelete(DeleteBehavior.Restrict);
    }
}
