using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class NotificationConfiguration : IEntityTypeConfiguration<Notification>
{
    public void Configure(EntityTypeBuilder<Notification> builder)
    {
        builder.ToTable("Notifications");

        builder.HasKey(n => n.NotificationId);

        builder.Property(n => n.Type)
            .IsRequired();

        // Unread until someone reads it. The default is in the database as well as in the CLR, so a
        // row inserted by anything other than this application starts out the same way.
        builder.Property(n => n.IsRead)
            .IsRequired()
            .HasDefaultValue(false);

        // Generated by the database, as everywhere else in this schema.
        builder.Property(n => n.CreatedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // Restrict, like every other user foreign key here: removing a user must never delete what
        // happened to somebody else.
        builder.HasOne(n => n.Recipient)
            .WithMany()
            .HasForeignKey(n => n.RecipientUserId)
            .OnDelete(DeleteBehavior.Restrict);

        builder.HasOne(n => n.Actor)
            .WithMany()
            .HasForeignKey(n => n.ActorUserId)
            .OnDelete(DeleteBehavior.Restrict);

        // Cascade: a notification points at a task and says nothing without it, so deleting the task
        // takes its notifications too rather than leaving rows that open nothing. This is the only
        // cascading path into the table — both user keys above are Restrict — so SQL Server has no
        // multiple-cascade-path to reject.
        builder.HasOne(n => n.Task)
            .WithMany()
            .HasForeignKey(n => n.TaskId)
            .OnDelete(DeleteBehavior.Cascade);

        // One index per query the API actually runs, and no more.

        // The badge: how many of this user's notifications are unread.
        builder.HasIndex(n => new { n.RecipientUserId, n.IsRead });

        // The panel: this user's notifications, newest first.
        builder.HasIndex(n => new { n.RecipientUserId, n.CreatedDate });
    }
}
