using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class TaskParticipantConfiguration : IEntityTypeConfiguration<TaskParticipant>
{
    public void Configure(EntityTypeBuilder<TaskParticipant> builder)
    {
        builder.ToTable("TaskParticipants");

        // The pair is the key, so adding the same user to the same task twice is impossible rather
        // than merely checked for. No uniqueness test in code, and no race between two requests.
        builder.HasKey(p => new { p.TaskId, p.UserId });

        // Generated by the database, as everywhere else.
        builder.Property(p => p.AddedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // Cascade: deleting a task takes its participation rows with it. Nothing else has to clean
        // up afterwards — team membership is derived from these rows, so a user whose last
        // participation went with the task simply stops being a member.
        builder.HasOne(p => p.Task)
            .WithMany(t => t.Participants)
            .HasForeignKey(p => p.TaskId)
            .OnDelete(DeleteBehavior.Cascade);

        // Restrict, like everywhere else: removing a user must never delete their work.
        builder.HasOne(p => p.User)
            .WithMany()
            .HasForeignKey(p => p.UserId)
            .OnDelete(DeleteBehavior.Restrict);

        // "Which boards is this user a member of" reads the participation rows by user.
        builder.HasIndex(p => p.UserId);

        // A task has at most one assignee. The composite key already stops the same user being
        // added twice; this stops a *second* user being added at all, so "zero or one" is a
        // database rule rather than something the service has to be trusted to uphold.
        builder.HasIndex(p => p.TaskId)
            .IsUnique();
    }
}
