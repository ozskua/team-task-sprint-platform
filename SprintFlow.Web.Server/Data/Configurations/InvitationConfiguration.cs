using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class InvitationConfiguration : IEntityTypeConfiguration<Invitation>
{
    /// <summary>SHA-256 is always 32 bytes, so the column is fixed-width rather than variable.</summary>
    private const int TokenHashLength = 32;

    public void Configure(EntityTypeBuilder<Invitation> builder)
    {
        builder.ToTable("Invitations");

        builder.HasKey(i => i.InvitationId);

        // Fixed length, and binary rather than text: the database collates Turkish_CI_AS, which is
        // case-insensitive, so a Base64 digest stored as nvarchar could compare equal to a different
        // digest. Bytes have no collation. Same class of problem the Users.Email collation pin fixes.
        builder.Property(i => i.TokenHash)
            .IsRequired()
            .HasColumnType($"varbinary({TokenHashLength})");

        builder.Property(i => i.ExpiresAt)
            .IsRequired();

        // Generated by the database, exactly as Users.CreatedDate is — the client can never supply
        // it, and it comes back with an unspecified kind so no timezone shifts it.
        builder.Property(i => i.CreatedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // The lookup path. Unique because a digest collision would mean two invitations answering to
        // one token, and redemption resolves a single row by this value.
        builder.HasIndex(i => i.TokenHash)
            .IsUnique()
            .HasDatabaseName("IX_Invitations_TokenHash");

        // "Which invitations did this user create" — the audit query.
        builder.HasIndex(i => i.InvitedByUserId)
            .HasDatabaseName("IX_Invitations_InvitedByUserId");

        // One invitation can never produce two accounts, and this is the database saying so rather
        // than the service. Filtered, because every open invitation has this column null and those
        // rows must not compete for uniqueness.
        builder.HasIndex(i => i.RegisteredUserId)
            .IsUnique()
            .HasFilter("[RegisteredUserId] IS NOT NULL")
            .HasDatabaseName("IX_Invitations_RegisteredUserId");

        // Restrict on both, for two reasons. Removing a user must never delete the record of who
        // they invited — and two cascading paths from one table to Users is what SQL Server refuses
        // outright (error 1785), the same constraint that forced Sprints → Tasks to Restrict.
        builder.HasOne(i => i.InvitedByUser)
            .WithMany()
            .HasForeignKey(i => i.InvitedByUserId)
            .OnDelete(DeleteBehavior.Restrict);

        builder.HasOne(i => i.RegisteredUser)
            .WithMany()
            .HasForeignKey(i => i.RegisteredUserId)
            .OnDelete(DeleteBehavior.Restrict);
    }
}
