using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SprintFlow.Web.Server.Models;

namespace SprintFlow.Web.Server.Data.Configurations;

public class TaskItemConfiguration : IEntityTypeConfiguration<TaskItem>
{
    public void Configure(EntityTypeBuilder<TaskItem> builder)
    {
        // The entity is TaskItem so it does not collide with System.Threading.Tasks.Task; the table
        // keeps the name the domain uses.
        builder.ToTable("Tasks");

        builder.HasKey(t => t.TaskId);

        builder.Property(t => t.Title)
            .IsRequired()
            .HasMaxLength(200);

        // Optional, so no IsRequired. Stored as null rather than an empty string.
        builder.Property(t => t.Description)
            .HasMaxLength(2000);

        // Generated by the database, as everywhere else.
        builder.Property(t => t.CreatedDate)
            .IsRequired()
            .HasDefaultValueSql("SYSUTCDATETIME()");

        // Cascade: a task cannot exist without its board.
        builder.HasOne(t => t.Board)
            .WithMany(b => b.Tasks)
            .HasForeignKey(t => t.BoardId)
            .OnDelete(DeleteBehavior.Cascade);

        // The composite foreign key is what makes "a task's column belongs to the same board" a
        // database rule rather than a check a service could forget. Pointing at the alternate key
        // above means the pair must match: a column id from another board has no matching
        // (WorkflowColumnId, BoardId) row and the insert is rejected outright.
        //
        // Restrict, not Cascade, for two reasons that happen to agree:
        //   * it is the deletion rule itself — a column still holding tasks cannot be removed, so
        //     no task is ever orphaned even if the service check were bypassed;
        //   * Boards already cascades to Tasks directly, and cascading here too would give SQL
        //     Server two cascade paths to the same table, which it rejects (error 1785).
        builder.HasOne(t => t.Column)
            .WithMany(c => c.Tasks)
            .HasForeignKey(t => new { t.TaskColumnId, t.BoardId })
            .HasPrincipalKey(c => new { c.WorkflowColumnId, c.BoardId })
            .OnDelete(DeleteBehavior.Restrict);

        // Restrict, like everywhere else: removing a user must never delete their work.
        builder.HasOne(t => t.CreatedByUser)
            .WithMany()
            .HasForeignKey(t => t.CreatedByUserId)
            .OnDelete(DeleteBehavior.Restrict);

        // Optional, and composite for the same reason the column relationship above is: naming the
        // sprint and the board together means a sprint from another board has no matching
        // (SprintId, BoardId) row and the insert is rejected outright, rather than relying on a
        // service check.
        //
        // SprintId is nullable, and SQL Server does not check a composite foreign key when any of
        // its columns is null — which is exactly right for a task that is in no sprint.
        //
        // Restrict, for the same two reasons as the column relationship:
        //   * it is the deletion rule itself — a sprint still holding tasks cannot be removed;
        //   * Boards already cascades to Tasks, and a second cascade path to the same table is
        //     rejected by SQL Server (error 1785).
        builder.HasOne(t => t.Sprint)
            .WithMany(s => s.Tasks)
            .HasForeignKey(t => new { t.SprintId, t.BoardId })
            .HasPrincipalKey(s => new { s.SprintId, s.BoardId })
            .OnDelete(DeleteBehavior.Restrict);

        // Reading a column means reading its tasks in order.
        builder.HasIndex(t => new { t.TaskColumnId, t.Position });

        // Team membership is derived by filtering tasks on their board, so that column is looked up
        // on its own often enough to index.
        builder.HasIndex(t => t.BoardId);

        // No index on SprintId alone. The sprint relationship above already produces
        // IX_Tasks_SprintId_BoardId, and SprintId leads it, so that index serves a lookup by sprint
        // on its own as well. A second one would only be another index to keep up to date on every
        // task written.
    }
}
