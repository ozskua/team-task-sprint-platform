namespace SprintFlow.Web.Server.Models;

// Metadata only. The bytes live on disk under the attachment root, named by StoredName, so the
// database stays small and a file the user uploaded can never be interpreted as a path.
public class TaskAttachment
{
    public int TaskAttachmentId { get; set; }

    public int TaskId { get; set; }

    // The comment this file was posted with, when it was posted with one. Null for a file attached
    // to the task on its own, which is how every file worked before comments carried them.
    public int? TaskCommentId { get; set; }

    // The name the uploader's file had. Shown to people and used for the download filename; never
    // touched by the filesystem.
    public string FileName { get; set; } = string.Empty;

    // The name on disk: a GUID plus the validated extension, generated by the server.
    public string StoredName { get; set; } = string.Empty;

    public string ContentType { get; set; } = string.Empty;

    public long SizeBytes { get; set; }

    public int UploadedByUserId { get; set; }

    public DateTime CreatedDate { get; set; }

    public TaskItem Task { get; set; } = null!;

    public TaskComment? Comment { get; set; }

    public User UploadedByUser { get; set; } = null!;
}
